    private void fillForm(int index) {
        lstNhanVien = nhanVienDAO.findAll();
        NhanVien entity = lstNhanVien.get(index);
        txtMaNV.setText(entity.getMaNV());
        txtSoDienThoai.setText(entity.getSdt());
        txtHoTen.setText(entity.getHoTen());
        txtmatKhau.setText(entity.getMatKhau());
        if (entity.getGioiTinh() == 1) {
            rdoNam.setSelected(true);
        } else {
            rdoNu.setSelected(true);
        }
        if (entity.getChucVu() == 1) {
            rdoQuanLy.setSelected(true);
        } else {
            rdoNhanVien.setSelected(true);
        }
        txtNgaySinh.setText(entity.getNgaySinh());
        if (entity.getTrangThai() == 1) {
            rdoDangLam.setSelected(true);
        } else {
            rdoNghiLam.setSelected(true);
        }
        txtID.setText(String.valueOf(entity.getId()));
        txtEmail.setText(entity.getEmail());
    }

