    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
        int check = tblNhanVien.getSelectedRow();
        if (check < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn dòng cần sửa!");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc là muốn sửa ?");
        if (confirm == JOptionPane.YES_OPTION) {
            if (txtHoTen.getText().isEmpty() || txtMaNV.getText().isEmpty() || txtNgaySinh.getText().isEmpty() || txtSoDienThoai.getText().isEmpty() || txtmatKhau.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập đủ các trường!");
                return;
            }

            if (txtSoDienThoai.getText().length() < 10 || !isValidVNPhone(txtSoDienThoai.getText())) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập số điện thoại hợp lệ!");
                return;
            }
            
            if (!isValidEmail(txtEmail.getText())) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập Email hợp lệ!");
                return;
            }
            
            String sdt = txtSoDienThoai.getText();
            for (NhanVien nv : nhanVienDAO.findAll()) {
                if (nv.getSdt().equalsIgnoreCase(sdt) && !txtMaNV.getText().equalsIgnoreCase(nv.getMaNV())) {
                    JOptionPane.showMessageDialog(this, "Không được nhập trùng số điện thoại của nhân viên khác!");
                    return;
                }
            }
            
            String mail = txtEmail.getText();
            for (NhanVien nv : nhanVienDAO.findAll()) {
                if (nv.getEmail().equalsIgnoreCase(mail) && !txtMaNV.getText().equalsIgnoreCase(nv.getMaNV())) {
                    JOptionPane.showMessageDialog(this, "Không được nhập trùng Email của nhân viên khác!");
                    return;
                }
            }

            NhanVien entity = new NhanVien();
            entity.setId(Integer.parseInt(txtID.getText()));
            entity.setMaNV(txtMaNV.getText());
            entity.setSdt(txtSoDienThoai.getText());
            entity.setHoTen(txtHoTen.getText());
            entity.setMatKhau(txtmatKhau.getText());
            if (rdoNam.isSelected()) {
                entity.setGioiTinh(1);
            } else {
                entity.setGioiTinh(0);
            }
            if (rdoQuanLy.isSelected()) {
                entity.setChucVu(1);
            } else {
                entity.setChucVu(0);
            }
            entity.setNgaySinh(txtNgaySinh.getText());
            if (rdoDangLam.isSelected()) {
                entity.setTrangThai(1);
            } else {
                entity.setTrangThai(0);
            }
            entity.setEmail(txtEmail.getText());
            nhanVienDAO.update(entity);
            fillToTable();
            JOptionPane.showMessageDialog(this, "Đã sửa thành công", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnSuaActionPerformed

