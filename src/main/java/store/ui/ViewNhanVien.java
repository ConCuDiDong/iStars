    @Override
    public void fillToTable() {
        DefaultTableModel model = (DefaultTableModel) tblNhanVien.getModel();
        model.setRowCount(0);
        lstNhanVien = nhanVienDAO.findAll();
        for (NhanVien nhanVien : lstNhanVien) {
            Object[] row = {
                nhanVien.getId(),
                nhanVien.getMaNV(),
                nhanVien.getHoTen(),
                nhanVien.getGioiTinh() == 1 ? "Nam" : "Nữ",
                nhanVien.getNgaySinh(),
                nhanVien.getSdt(),
                nhanVien.getMatKhau(),
                nhanVien.getChucVu() == 1 ? "Quản lý" : "Nhân viên",
                nhanVien.getEmail(),
                nhanVien.getTrangThai() == 1 ? "Đang làm" : "Nghỉ làm"
            };
            model.addRow(row);
        }
    }

